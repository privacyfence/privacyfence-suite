#!/usr/bin/env bash
# Bootstrap a fresh Ubuntu/Debian Hetzner VM into: Tailscale SSH + ufw + Docker + nginx (nginx.org)
# + Let's Encrypt cert via Cloudflare DNS-01 + the privacyfence-suite "nginx-google" configuration.
#
# Usage (as root, config in /root/pf-deploy.env):
#   ./bootstrap.sh all          # everything except locking public SSH
#   ./bootstrap.sh lock-ssh     # after you verified `ssh <user>@<ts-hostname>` over Tailscale
#   ./bootstrap.sh <step>       # base | tailscale | docker | nginx | cert | suite | firewall | cf-refresh
# Every step is idempotent.
set -euo pipefail

ENV_FILE=${PF_DEPLOY_ENV:-/root/pf-deploy.env}
HERE=$(cd "$(dirname "$0")" && pwd)
SUITE_DIR=${SUITE_DIR:-/opt/privacyfence-nginx-google}

log() { printf '\n==> %s\n' "$*"; }
die() { printf 'bootstrap: %s\n' "$*" >&2; exit 1; }
[ "$(id -u)" = 0 ] || die "run as root"
[ -f "$ENV_FILE" ] || die "missing $ENV_FILE (copy pf-deploy.env.example)"
[ "$(stat -c %a "$ENV_FILE")" = 600 ] || die "chmod 600 $ENV_FILE (it holds secrets)"
set -a; . "$ENV_FILE"; set +a
: "${PF_HOSTNAME:?}" "${PEEK_HOSTNAME:?}" "${GRIST_HOSTNAME:?}"
. /etc/os-release
case "$ID" in ubuntu|debian) ;; *) die "Ubuntu or Debian only (got $ID)";; esac
export DEBIAN_FRONTEND=noninteractive
CERT_DIR=/etc/letsencrypt/live/$PF_HOSTNAME

need() { for v in "$@"; do [ -n "${!v:-}" ] || die "set $v in $ENV_FILE"; done; }

step_base() {
  log "base packages, unattended upgrades"
  apt-get update -qq
  apt-get install -y -qq ca-certificates curl gnupg ufw unattended-upgrades jq cron
  systemctl enable --now cron
}

step_tailscale() {
  need TS_AUTHKEY
  log "tailscale"
  if ! command -v tailscale >/dev/null; then curl -fsSL https://tailscale.com/install.sh | sh; fi
  if ! tailscale status >/dev/null 2>&1; then
    tailscale up --ssh --authkey="$TS_AUTHKEY" --hostname="${TS_HOSTNAME:-pf-suite}"
  fi
  tailscale status | head -3
}

step_docker() {
  log "docker engine"
  if ! command -v docker >/dev/null; then curl -fsSL https://get.docker.com | sh; fi
  systemctl enable --now docker
  docker compose version
}

step_nginx() {
  log "nginx (nginx.org stable; Ubuntu/Debian packages are older than the 1.25.1 the suite needs)"
  install -d -m 0755 /etc/apt/keyrings
  curl -fsSL https://nginx.org/keys/nginx_signing.key | gpg --dearmor -o /etc/apt/keyrings/nginx.gpg --yes
  gpg --show-keys --with-colons /etc/apt/keyrings/nginx.gpg | grep -q 573BFD6B3D8FBC641079A6ABABF5BD827BD9BF62 \
    || die "nginx signing key fingerprint mismatch"
  echo "deb [signed-by=/etc/apt/keyrings/nginx.gpg] https://nginx.org/packages/$ID $VERSION_CODENAME nginx" \
    > /etc/apt/sources.list.d/nginx.list
  printf 'Package: *\nPin: origin nginx.org\nPin-Priority: 900\n' > /etc/apt/preferences.d/99nginx
  apt-get update -qq
  apt-get install -y -qq nginx
  rm -f /etc/nginx/conf.d/default.conf
  nginx -v
  systemctl enable nginx
}

step_cf_refresh() {
  log "cloudflare ip ranges -> nginx real_ip + ufw"
  [ "$(readlink -f "$0")" = /usr/local/sbin/pf-bootstrap.sh ] || install -m 0755 "$0" /usr/local/sbin/pf-bootstrap.sh
  local v4 v6 tmp
  v4=$(curl -fsS https://www.cloudflare.com/ips-v4) ; v6=$(curl -fsS https://www.cloudflare.com/ips-v6)
  [ -n "$v4" ] && [ -n "$v6" ] || die "could not fetch Cloudflare ranges"
  tmp=$(mktemp)
  { echo "# generated by pf-bootstrap.sh cf-refresh; Cloudflare only"
    for r in $v4 $v6; do echo "set_real_ip_from $r;"; done
    echo "real_ip_header CF-Connecting-IP;"; } > "$tmp"
  install -m 0644 "$tmp" /etc/nginx/conf.d/00-cloudflare-realip.conf; rm -f "$tmp"
  printf '%s\n%s\n' "$v4" "$v6" > /etc/pf-cloudflare-ranges
  if ufw status | grep -q 'Status: active'; then apply_cf_ufw; fi
  if [ -f /etc/nginx/conf.d/privacyfence-suite.conf ]; then nginx -t && systemctl reload nginx; fi
  # weekly: refresh Cloudflare's ranges (the installed copy reads /root/pf-deploy.env)
  printf '#!/bin/sh\nexec /usr/local/sbin/pf-bootstrap.sh cf-refresh\n' > /etc/cron.weekly/pf-cf-refresh
  chmod 0755 /etc/cron.weekly/pf-cf-refresh
}

apply_cf_ufw() {
  # replace previous Cloudflare rules (tagged with a comment) with the current list
  ufw status numbered | { grep 'pf-cf-443' || true; } | sed -E 's/^\[ *([0-9]+)\].*/\1/' | sort -rn | while read -r n; do
    ufw --force delete "$n" >/dev/null
  done
  while read -r r; do ufw allow proto tcp from "$r" to any port 443 comment pf-cf-443 >/dev/null; done < /etc/pf-cloudflare-ranges
}

step_cert() {
  need CF_API_TOKEN LE_EMAIL
  log "let's encrypt (DNS-01 through Cloudflare): one cert for the three names"
  apt-get install -y -qq certbot python3-certbot-dns-cloudflare
  install -d -m 0700 /root/.secrets
  printf 'dns_cloudflare_api_token = %s\n' "$CF_API_TOKEN" > /root/.secrets/cloudflare.ini
  chmod 600 /root/.secrets/cloudflare.ini
  certbot certonly --non-interactive --agree-tos -m "$LE_EMAIL" \
    --dns-cloudflare --dns-cloudflare-credentials /root/.secrets/cloudflare.ini \
    --dns-cloudflare-propagation-seconds 30 \
    --cert-name "$PF_HOSTNAME" -d "$PF_HOSTNAME" -d "$PEEK_HOSTNAME" -d "$GRIST_HOSTNAME"
  install -d /etc/letsencrypt/renewal-hooks/deploy
  printf '#!/bin/sh\nsystemctl reload nginx\n' > /etc/letsencrypt/renewal-hooks/deploy/reload-nginx
  chmod 0755 /etc/letsencrypt/renewal-hooks/deploy/reload-nginx
}

step_suite() {
  need ALLOWED_DOMAIN ADMIN_EMAILS GRIST_ADMIN_EMAIL
  log "privacyfence-suite (nginx-google)"
  [ -d "$CERT_DIR" ] || die "no certificate yet: run the cert step first"
  if [ ! -d "$SUITE_DIR" ]; then
    local base=https://github.com/privacyfence/privacyfence-suite/releases/latest/download w
    [ -z "${SUITE_VERSION:-}" ] || base=https://github.com/privacyfence/privacyfence-suite/releases/download/v$SUITE_VERSION
    w=$(mktemp -d)
    curl -fsSL -o "$w/install.sh" "$base/install.sh"; curl -fsSL -o "$w/SHA256SUMS" "$base/SHA256SUMS"
    (cd "$w" && sha256sum -c --ignore-missing SHA256SUMS)
    (cd "$w" && sh install.sh nginx-google --dir "$SUITE_DIR")
    rm -rf "$w"
  fi
  cd "$SUITE_DIR"
  local f=.env
  setv() { # setv KEY VALUE: replace the (possibly commented) assignment, or append
    if grep -q "^$1=" $f; then sed -i "s|^$1=.*|$1=$2|" $f; else echo "$1=$2" >> $f; fi
  }
  setv PF_HOSTNAME "$PF_HOSTNAME"; setv PEEK_HOSTNAME "$PEEK_HOSTNAME"; setv GRIST_HOSTNAME "$GRIST_HOSTNAME"
  setv ADMIN_EMAILS "$ADMIN_EMAILS"; setv ALLOWED_DOMAIN "$ALLOWED_DOMAIN"
  setv GRIST_ADMIN_EMAIL "$GRIST_ADMIN_EMAIL"; setv PEEK_ADMIN_EMAILS "${PEEK_ADMIN_EMAILS:-}"
  [ -z "${PRIVACYFENCE_IMAGE_TAG:-}" ] || setv PRIVACYFENCE_IMAGE_TAG "$PRIVACYFENCE_IMAGE_TAG"

  sed -e "s|@PF@|$PF_HOSTNAME|g" -e "s|@PEEK@|$PEEK_HOSTNAME|g" -e "s|@GRIST@|$GRIST_HOSTNAME|g" \
      -e "s|@CERT_DIR@|$CERT_DIR|g" "$HERE/site.conf.template" > /etc/nginx/conf.d/privacyfence-suite.conf
  nginx -t && systemctl reload nginx || systemctl restart nginx

  docker compose up -d
  docker compose ps
}

step_firewall() {
  log "ufw: SSH stays open on the public IP until lock-ssh; 443 only from Cloudflare + the pf-suite bridge"
  ufw default deny incoming; ufw default allow outgoing
  ufw allow in on tailscale0 comment tailscale
  ufw allow 22/tcp comment 'ssh-until-lock'
  ufw allow in on pf-suite to any port 443 proto tcp comment pf-suite-bridge
  [ -f /etc/pf-cloudflare-ranges ] || step_cf_refresh
  apply_cf_ufw
  ufw --force enable
  ufw status verbose
}

step_lock_ssh() {
  tailscale status >/dev/null 2>&1 || die "tailscale is not up; refusing to lock out SSH"
  log "removing public SSH (port 22). Make sure 'ssh root@$(tailscale ip -4 | head -1)' works from another terminal first."
  read -r -p "Verified SSH over Tailscale? type yes: " a; [ "$a" = yes ] || die aborted
  ufw status numbered | { grep 'ssh-until-lock' || true; } | sed -E 's/^\[ *([0-9]+)\].*/\1/' | sort -rn | while read -r n; do
    ufw --force delete "$n" >/dev/null
  done
  ufw status
}

case "${1:-}" in
  all) step_base; step_tailscale; step_docker; step_nginx; step_cert; step_cf_refresh; step_firewall; step_suite
       log "done. Next: docs in $HERE/README.md (relay DNS records, Cloudflare SSL mode, ./bootstrap.sh lock-ssh)";;
  base|tailscale|docker|nginx|cert|suite|firewall) "step_$1";;
  cf-refresh) step_cf_refresh;;
  lock-ssh) step_lock_ssh;;
  *) sed -n 2,9p "$0"; exit 2;;
esac
